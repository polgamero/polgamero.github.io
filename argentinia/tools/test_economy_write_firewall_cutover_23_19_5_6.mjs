const constants = read(new URL('../../functions/src/shared/constants.js', import.meta.url));
const config = read(new URL('../../functions/src/economy/config.js', import.meta.url));
const index = read(new URL('../../functions/src/index.js', import.meta.url));
const impl = read(new URL('../js/firebaseClientImpl.js', import.meta.url));
const ui = read(new URL('../js/ui.js', import.meta.url));
const clientFacade = read(new URL('../js/firebaseClient.js', import.meta.url));
const manifest = JSON.parse(read(new URL('../build-manifest.json', import.meta.url)));

assert.match(constants, /mode: ECONOMY_MODES\.SERVER_REQUIRED/);
assert.match(constants, /minInstances: 0/);
assert.match(constants, /maxInstances: 1/);
assert.match(constants, /concurrency: 10/);
assert.match(constants, /enforceAppCheck: false/);
