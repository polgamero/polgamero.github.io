assert.doesNotMatch(impl.slice(impl.indexOf('export async function recordPlayerGameResult'), impl.indexOf('export async function fetchPublicPlayerStats')), /trackPlayerStats\(/);

assert.match(impl, /export async function fetchEconomyAuditForAdmin/);
assert.match(impl, /collection\(db, 'economyEvents'\)/);
assert.match(impl, /collection\(db, 'adminActions'\)/);
assert.match(clientFacade, /fetchEconomyAuditForAdmin/);
assert.match(ui, /data-admin-pane="economyAudit"/);
assert.match(ui, /ECONOMÍA \/ AUDITORÍA|admin\.tab\.economyAudit/);
assert.match(ui, /admin-economy-audit-export/);
assert.match(ui, /operationId/);

